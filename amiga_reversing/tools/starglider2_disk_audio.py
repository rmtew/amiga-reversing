"""Hash-bound source audit of Starglider 2 disk codecs and streamed music.

No disk formatting, guest execution, PCM/output equivalence or media creation.
The arithmetic models data tables, not 68000 opcode execution.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import struct
from pathlib import Path
from .starglider2_protection import IMAGE_SHA256


def mfm_word(value: int, previous_data_bit: int = 1) -> int:
    if not 0 <= value <= 255 or previous_data_bit not in (0, 1):
        raise ValueError('Expected a byte and one preceding data bit')
    result = 0
    previous = previous_data_bit
    for shift in range(7, -1, -1):
        bit = value >> shift & 1
        result = result << 2 | (int(not (previous or bit)) << 1) | bit
        previous = bit
    return result


def decode_nibble(value: int) -> int:
    if not 0 <= value <= 127:
        raise ValueError('Expected the original masked 7-bit lookup index')
    return sum(((value >> (2*i)) & 1) << i for i in range(4))


def audit(payload: bytes) -> dict[str, object]:
    if len(payload) != 412736 or hashlib.sha256(payload).hexdigest() != IMAGE_SHA256:
        raise ValueError('Expected the reviewed Starglider 2 main-copy image')
    encoded = struct.unpack_from('>256H', payload, 0x10F16)
    decoded = payload[0x11116:0x11196]
    if encoded != tuple(mfm_word(value) for value in range(256)):
        raise ValueError('Stored MFM byte-to-WORD table differs')
    if decoded != bytes(decode_nibble(value) for value in range(128)):
        raise ValueError('Stored MFM nibble decoder differs')
    if payload[0x11428:0x11628] != bytes(512):
        raise ValueError('Original generated CRC-table seed is not zero')
    if payload[0x4C0CA:0x4C0F2] != bytes(40):
        raise ValueError('Original channel3 silence seed differs')
    return dict(schema_version=1, binary_sha256=IMAGE_SHA256,
        codecs=dict(encode_table=[0x11F16, 0x12116], encode_entries=256,
                    decode_table=[0x12116, 0x12196], decode_entries=128,
                    crc_tables=[0x12428, 0x12628], crc_polynomial=0x1021,
                    crc_seed='512 original zero bytes; generated by $10DEC'),
        music=dict(entry=0x10260, slots=7, slot_bytes=5632, total_ring_bytes=39424,
                   normal_track_profile=[512]*10,
                   music_track_profile=[1024]*5+[512], music_first_sector_id=0xF5,
                   streamed_blocks=80, total_audio_bytes=450560,
                   cache_span=[0xC00000, 0xC6E000],
                   producer_control_word=0x10592,
                   direct_disk_flag=0x1059A, cache_loaded_flag=0x1059B,
                   original_amiga_probe='CMP is followed by NOP then ST direct-disk flag; do not repair or assume cache selected'),
        saved_state=dict(pointer_normalize=0x105C6, pointer_restore=0x106AC,
                         app_start=0x6B4, app_end=0x6598, copied_bytes=24292,
                         staging_bytes=25600, tracks=5),
        channel3_initial_silence=[0x4D0CA, 0x4D0F2],
        limits=['Static original source contracts, not exercised disk/music operations',
                'No assumption that supplied ADF contains the custom music media',
                'Original NOP/probe behavior and unchecked inputs preserved',
                'Shared workspace lifetimes and complete DMA/PCM coverage remain unproved'])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('image', type=Path)
    args = parser.parse_args()
    print(json.dumps(audit(args.image.read_bytes()), indent=2))

if __name__ == '__main__':
    main()
